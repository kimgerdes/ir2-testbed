"""Live demo on SciFact: BM25 and bge-small (spring baselines) next to LLM2Vec (Qwen2.5-0.5B, full recipe).

Nothing is trained or indexed during the demo:
  python method.py --name full --mode bi --adapters outputs/q05/mntp outputs/q05/mntp-simcse   (LLM2Vec documents)
  python demo.py --prepare                                                                   (bge documents and BM25)
  python demo.py
Then type a claim, or a shortcut: hero, fail, wild1, wild2, wild3 (see demo.md). Empty line or q to quit.
"""
import argparse
import pickle
import sys
import time
import warnings
from pathlib import Path

import numpy as np
from rich.console import Console
from rich.table import Table

from method import INSTRUCTIONS, testbed

HERE = Path(__file__).resolve().parent
INDEX = HERE / "runs" / "demo"
ADAPTERS = ["outputs/q05/mntp", "outputs/q05/mntp-simcse"]
TOP = 5
SHORTCUTS = {
    "hero": "0-dimensional biomaterials show inductive properties.",
    "fail": "Insulin increases risk of severe kidney failure.",
    "wild1": "Individuals with low serum vitamin D concentrations have increased risk of multiple sclerosis.",
    "wild2": "People who get little sunshine are more likely to develop MS.",
    "wild3": "The single flash-evoked ERG b-wave is generated by activity of ON-bipolar cells.",
}
# our own rewording of a SciFact query: we show the labelled doc of the original query
PARAPHRASE_OF = {SHORTCUTS["wild2"]: SHORTCUTS["wild1"]}


def bm25_tools():
    # same preprocessing as testbed.bm25_search
    import nltk
    from nltk.corpus import stopwords
    from nltk.stem import PorterStemmer
    from sklearn.feature_extraction.text import CountVectorizer
    nltk.download("stopwords", quiet=True)
    sw, porter, analyze = set(stopwords.words("english")), PorterStemmer(), CountVectorizer().build_analyzer()
    return lambda t: [porter.stem(x) for x in analyze(t) if x not in sw]


def prepare(corpus):
    from rank_bm25 import BM25Okapi
    from sentence_transformers import SentenceTransformer
    INDEX.mkdir(parents=True, exist_ok=True)
    texts = testbed.doc_texts(corpus)
    preprocess = bm25_tools()
    pickle.dump(BM25Okapi([preprocess(t) for t in texts], k1=1.2, b=0.75), open(INDEX / "bm25.pkl", "wb"))
    bge = SentenceTransformer("BAAI/bge-small-en-v1.5", device="cpu")
    np.save(INDEX / "bge_docs.npy", bge.encode(texts, batch_size=64, normalize_embeddings=True, show_progress_bar=True))
    print(f"wrote {INDEX}")


class Demo:
    def __init__(self, corpus, queries, qrels):
        from sentence_transformers import SentenceTransformer
        from encoder import load_model, load_tokenizer
        self.ids = list(corpus)
        self.titles = [corpus[d]["title"] for d in self.ids]
        self.texts = testbed.doc_texts(corpus)
        # if the claim is a SciFact query we know its labelled documents
        self.labels = {queries[q]: {d for d, g in qrels[q].items() if g > 0} for q in queries}
        self.preprocess = bm25_tools()
        self.bm25 = pickle.load(open(INDEX / "bm25.pkl", "rb"))
        self.bge = SentenceTransformer("BAAI/bge-small-en-v1.5", device="cpu")
        self.bge_docs = np.load(INDEX / "bge_docs.npy")
        self.tok = load_tokenizer("Qwen/Qwen2.5-0.5B")
        self.model = load_model("Qwen/Qwen2.5-0.5B", [str(HERE / a) for a in ADAPTERS])
        self.ours_docs = np.load(HERE / "runs" / "full" / "scifact_docs.npy")
        self.scores("warm up")  # the first call on MPS is slow

    def scores(self, claim):
        from encoder import encode
        q_ours = encode(self.model, self.tok, [claim], "bi", instruction=INSTRUCTIONS["scifact"], max_length=512)[0]
        q_bge = self.bge.encode(testbed.BGE_QUERY + claim, normalize_embeddings=True)
        return {"BM25": self.bm25.get_scores(self.preprocess(claim)),
                "bge-small": self.bge_docs @ q_bge,
                "LLM2Vec Qwen2.5-0.5B": self.ours_docs @ q_ours}

    def show(self, console, claim):
        t0 = time.time()
        scores = self.scores(claim)
        seconds = time.time() - t0
        labelled = self.labels.get(PARAPHRASE_OF.get(claim, claim), set())
        table = Table(show_lines=True, expand=True)
        for name in scores:
            table.add_column(name, ratio=1)
        tops = {name: np.argsort(-s)[:TOP] for name, s in scores.items()}
        for r in range(TOP):
            cells = []
            for name in scores:
                j = tops[name][r]
                mark = "[bold green]✓ [/]" if self.ids[j] in labelled else ""
                cells.append(f"{mark}{r + 1}. {self.titles[j][:90]}")
            table.add_row(*cells)
        console.print(table)
        if labelled:
            for d in sorted(labelled):
                j = self.ids.index(d)
                ranks = []
                for name, s in scores.items():
                    rank = int((s > s[j]).sum()) + 1
                    ranks.append(f"{name} [bold]{rank}[/]")
                shared = sorted(set(self.preprocess(claim)) & set(self.preprocess(self.texts[j])))
                console.print(f"[green]labelled doc[/] {self.titles[j][:100]}")
                console.print("  rank: " + " | ".join(ranks) + f"   (of {len(self.ids)} docs)")
                console.print(f"  shared word stems with the claim: {', '.join(shared) if shared else 'none'}")
        else:
            console.print("[dim]not a SciFact query: no labelled document[/]")
        console.print(f"[dim]encoding the claim took {seconds:.2f} s[/]\n")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--prepare", action="store_true", help="build the bge and BM25 indexes once")
    args = p.parse_args()
    corpus, queries, qrels = testbed.load("scifact")
    if args.prepare:
        return prepare(corpus)
    # a clean screen for the demo: no warnings, no progress bars, no automatic colors
    import transformers
    warnings.filterwarnings("ignore")
    transformers.logging.set_verbosity_error()
    transformers.logging.disable_progress_bar()
    console = Console(highlight=False)
    with console.status("loading the models"):
        demo = Demo(corpus, queries, qrels)
    console.print(f"SciFact, {len(corpus)} documents. Type a claim or a shortcut ({', '.join(SHORTCUTS)}).\n")
    while True:
        try:
            claim = console.input("[bold]claim> [/]").strip()
        except (EOFError, KeyboardInterrupt):
            break
        if claim in ("", "q"):
            break
        claim = SHORTCUTS.get(claim, claim)
        console.print(f"[bold]{claim}[/]")
        demo.show(console, claim)


if __name__ == "__main__":
    sys.exit(main())
